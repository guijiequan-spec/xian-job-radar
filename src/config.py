def detect_company_nature(company: str) -> str:
    """根据公司名关键词打标。仅用于分类展示，非官方认证。"""
    if not company:
        return "未识别"
    c = company.upper()
    for kw in CENTRAL_SOKEYS:
        kw = kw.replace("//", "").strip()
        if kw and kw in company:
            return "央国企"
    for kw in FOREIGN_SOKEYS:
        kw = kw.replace("//", "").strip()
        if kw and kw.upper() in c:
            return "外企"
    for kw in TOP_PRIVATE_SOKEYS:
        kw = kw.replace("//", "").strip()
        if kw and kw in company:
            return "头部民企"
    return "其他"


